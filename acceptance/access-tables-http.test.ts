import { expect, it } from "vitest";
import { createCompany } from "@/application/companies";
import { acceptInvitation, generateInvitationLink, listAccessManagement } from "@/application/memberships";
import { administratorWithCompany, companyDetails, companyMember } from "../tests/support/fixtures";
import { provisionedAccount } from "../tests/support/clients";
import { httpAs, value } from "./support/http";

it("returns one localized User table row with concrete Membership details, separate scoped Invitations and authorized email search", async () => {
  const owner = await administratorWithCompany("HTTP access tables");
  const second = value(await createCompany(owner.client, { organizationId: owner.organizationId, ...companyDetails({ name: "Second scope" }) }));
  const member = await provisionedAccount({ email: `long-${crypto.randomUUID()}-multiple-scopes@long-company-account.example.test`, password: "correct-horse-battery", organizationName: "Long email account" });
  const firstInvitation = value(await generateInvitationLink(owner.client, { organizationId: owner.organizationId, companyId: owner.companyId, email: member.email, role: "user", acceptUrl: "http://localhost/invitations/accept" }));
  value(await acceptInvitation(member.client, firstInvitation.token));
  const invitation = value(await generateInvitationLink(owner.client, { organizationId: owner.organizationId, companyId: second.id, email: member.email, role: "administrator", acceptUrl: "http://localhost/invitations/accept" }));
  value(await acceptInvitation(member.client, invitation.token));
  value(await generateInvitationLink(owner.client, { organizationId: owner.organizationId, companyId: null, email: "table-invitation@example.test", role: "administrator", acceptUrl: "http://localhost/invitations/accept" }));
  const request = await httpAs(owner.client);
  const path = `/organizations/${owner.organizationId}/users`;
  const response = await request(path);
  expect(response.status).toBe(200);
  const html = await response.text();
  const tables = [...html.matchAll(/<table\b[^>]*>[\s\S]*?<\/table>/g)].map(match => match[0]);
  expect(tables).toHaveLength(2);
  const userRows = [...tables[0].matchAll(/<tr\b[^>]*>[\s\S]*?<\/tr>/g)].map(match => match[0]);
  const [userRow] = userRows.filter(row => row.includes(member.email));
  expect(userRows.filter(row => row.includes(member.email))).toHaveLength(1);
  expect(userRow).toContain("<details");
  expect(userRow).toContain("<summary");
  expect(userRow).toContain("Second scope");
  expect(userRow).toContain("Novák s.r.o.");
  const access = value(await listAccessManagement(owner.client, { organizationId: owner.organizationId, companyId: null }));
  for (const membership of access.users.find(user => user.userId === member.userId)!.memberships) expect(userRow).toContain(membership.id);
  expect(tables[0]).not.toContain("table-invitation@example.test");
  expect(tables[1]).toContain("table-invitation@example.test");
  expect(tables[1]).toContain("Organization: HTTP access tables");
  expect(tables[1]).toContain("Pending");
  expect(tables[1]).toContain("Copy link");
  expect(tables[1]).toContain("Cancel invitation");
  const searched = await (await request(`${path}?email=${encodeURIComponent(member.email.toUpperCase())}`)).text();
  expect(searched).toContain(member.email);
  expect(searched.match(/<table\b[^>]*>[\s\S]*?<\/table>/)?.[0]?.includes(owner.email)).toBe(false);
  const empty = await (await request(`${path}?email=no-match%40example.test`)).text();
  expect(empty).toContain("No users match this email in the selected scope.");
  expect(empty.includes(member.email)).toBe(false);
  const company = await (await request(`${path}?scope=${owner.companyId}`)).text();
  expect(company).not.toContain("table-invitation@example.test");
  expect(company).toContain("Effective Access");
  const administrator = await companyMember(owner, "administrator");
  const denied = await (await httpAs(administrator.client))(`/companies/${owner.companyId}/settings/users?scope=${second.id}&email=${encodeURIComponent(member.email)}`);
  const deniedHtml = await denied.text();
  expect(deniedHtml).toContain("You cannot manage this scope.");
  expect(deniedHtml.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, "").includes(member.email)).toBe(false);
  const czech = await (await (await httpAs(owner.client, "cs"))(path)).text();
  expect(czech).toContain("Zobrazit členství");
  expect(czech).toContain("Hledat podle e-mailu");
});
