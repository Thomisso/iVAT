import fontkit from "@pdf-lib/fontkit";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { PDFDocument, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import type { AppClient, Result } from "./client";
import { registeredAddressLine } from "./companies";
import type { VatReturnPreviewData } from "./vat-return-preview";
import { vatReturnPreviewData } from "./vat-return-preview";
import { getVatReport } from "./vat-reports";

const fontPath = path.join(
  process.cwd(),
  "node_modules/next/dist/compiled/@vercel/og/Geist-Regular.ttf",
);

const LABELS = {
  outputVat: "Output VAT",
  inputVat: "Input VAT deduction",
  payable: "VAT payable",
  excessDeduction: "Excess deduction",
} as const;

function text(
  page: PDFPage,
  font: PDFFont,
  value: string,
  x: number,
  y: number,
  size = 10,
) {
  page.drawText(value, { x, y, size, font, color: rgb(0.08, 0.1, 0.13) });
}

function rightAligned(
  page: PDFPage,
  font: PDFFont,
  value: string,
  right: number,
  y: number,
  size = 10,
) {
  text(page, font, value, right - font.widthOfTextAtSize(value, size), y, size);
}

/** Renders the same saved data shown by the HTML VAT Return preview. */
export async function createVatReturnPdf(
  preview: VatReturnPreviewData,
): Promise<Uint8Array> {
  const document = await PDFDocument.create();
  document.registerFontkit(fontkit);
  const font = await document.embedFont(await readFile(fontPath), {
    subset: true,
  });
  const page = document.addPage([595.28, 841.89]);
  const { width } = page.getSize();
  const left = 42;
  const right = width - 42;

  text(page, font, "iVAT · VAT Return (DPHDP3)", left, 798, 18);
  text(page, font, preview.company.name, left, 767, 13);
  text(page, font, `VAT ID: ${preview.company.vatId}`, left, 747);
  text(page, font, `IČO: ${preview.company.ico}`, left, 731);
  text(page, font, `Address: ${registeredAddressLine(preview.company)}`, left, 715);
  text(
    page,
    font,
    `${preview.company.postalCode} ${preview.company.city}`,
    left + 48,
    699,
  );
  text(page, font, `Reporting Period: ${preview.period}`, left, 675, 11);

  page.drawRectangle({
    x: left,
    y: 642,
    width: right - left,
    height: 23,
    color: rgb(0.91, 0.94, 0.97),
  });
  text(page, font, "VAT Return line", left + 6, 650);
  rightAligned(page, font, "Tax base (CZK)", right - 114, 650);
  rightAligned(page, font, "VAT (CZK)", right - 6, 650);

  preview.lines.forEach((line, index) => {
    const rowTop = 642 - index * 23;
    const y = rowTop - 15;
    page.drawLine({
      start: { x: left, y: rowTop - 23 },
      end: { x: right, y: rowTop - 23 },
      thickness: 0.5,
      color: rgb(0.78, 0.8, 0.83),
    });
    text(page, font, `Line ${line.line}`, left + 6, y);
    rightAligned(page, font, line.netAmount, right - 114, y);
    rightAligned(page, font, line.vatAmount, right - 6, y);
  });

  const totalsTop = 320;
  text(page, font, "Totals", left, totalsTop, 13);
  (Object.keys(LABELS) as (keyof typeof LABELS)[]).forEach((key, index) => {
    const y = totalsTop - 24 - index * 20;
    text(page, font, LABELS[key], left + 6, y);
    rightAligned(page, font, preview.totals[key], right - 6, y);
  });

  document.setTitle(`VAT Return ${preview.period} · ${preview.company.name}`);
  document.setSubject("VAT Return PDF preview generated by iVAT");
  return document.save();
}

export type VatReturnPdfDownload = {
  bytes: Uint8Array;
  fileName: string;
  mediaType: "application/pdf";
};

/** RLS scopes the saved snapshot before any PDF bytes are produced. */
export async function exportVatReturnPdf(
  client: AppClient,
  input: { companyId: string; period: string },
): Promise<Result<VatReturnPdfDownload, "report_not_found">> {
  const report = await getVatReport(client, input.companyId, input.period);
  if (!report) return { ok: false, error: "report_not_found" };
  return {
    ok: true,
    value: {
      bytes: await createVatReturnPdf(vatReturnPreviewData(report.result)),
      fileName: `DPHDP3-${input.period}.pdf`,
      mediaType: "application/pdf",
    },
  };
}
