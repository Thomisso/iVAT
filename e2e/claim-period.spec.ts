import { expect, test } from "@playwright/test";
import { provisionAndLogIn } from "./support/accounts";
import { browserUserClient } from "../tests/support/e2e";
import { SAMPLE_EXTRACTION } from "../src/ai/fake";
import { createManualDocument, listExtractionVersions } from "../src/application/documents";
import { generateVatReport, finalizeVatReport } from "../src/application/vat-reports";
import { fakeVatPayerRegistry } from "../src/vat-registry/fake";

test("an accountant explicitly confirms source-less eligibility and history/locks retain its origin", async ({ page, context, baseURL }) => {
  if (!baseURL) throw new Error("base URL required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = crypto.randomUUID();
  await provisionAndLogIn(page, { organizationName: `Claim ${run}`, email: `claim-${run}@example.test`, password: "Claim-period-browser-237" });
  await page.getByLabel("Company name").fill(`Claim ${run}`);
  await page.getByLabel("IČO").fill("25596641");
  await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská");
  await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha");
  await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  const client = await browserUserClient(await context.cookies());
  const created = await createManualDocument(client, { companyId, payload: { ...SAMPLE_EXTRACTION, documentType: null } }, undefined, fakeVatPayerRegistry());
  if (!created.ok) throw new Error(created.error);
  const href = `/companies/${companyId}/documents/${created.value.id}`;
  await page.goto(href);
  await expect(page.getByLabel("Document type", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await expect(page.getByText("Choose a Document type before confirming claim eligibility.", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "Approve version 1", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Choose a Document type before confirming claim eligibility." })).toBeVisible();
  await expect(page.getByRole("button", { name: "Approve version 1", exact: true })).toBeEnabled();
  await page.getByLabel("Document type", { exact: true }).selectOption("invoice");
  await expect(page.getByLabel("Document type", { exact: true })).toHaveValue("invoice");
  await expect(page.getByRole("group", { name: "Earliest Claim Period", exact: true })).toContainText("Confirmation required");
  await expect(page.getByRole("combobox", { name: "First eligible period", exact: true })).toBeVisible();
  await page.getByLabel("First eligible period", { exact: true }).selectOption("2026-10", { timeout: 10_000 });
  await page.getByRole("checkbox", { name: "I confirm the eligibility conditions were met in the selected period.", exact: true }).check();
  await expect(page.getByLabel("Document type", { exact: true })).toHaveValue("invoice");
  await page.getByLabel("Issue date", { exact: true }).fill("2.10.2026");
  await expect(page.getByRole("checkbox", { name: "I confirm the eligibility conditions were met in the selected period.", exact: true })).not.toBeChecked();
  await page.getByRole("checkbox", { name: "I confirm the eligibility conditions were met in the selected period.", exact: true }).check();
  await page.getByRole("button", { name: "Approve version 1", exact: true }).click();
  await expect(page).toHaveURL(/\/documents(?:\?.*)?$/);
  const versions = await listExtractionVersions(client, companyId, created.value.id);
  expect(versions[0].payload.claimEligibility).toBeUndefined();
  expect(versions[1].payload.claimEligibility).toMatchObject({ period: "2026-10", origin: "user", confirmed: true, basis: { importDate: null } });
  await page.goto(`${href}?version=1`);
  await expect(page.getByLabel("First eligible period", { exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Save reporting period", exact: true })).toHaveCount(0);
  await page.goto(href);
  await expect(page.getByRole("group", { name: "Earliest Claim Period", exact: true })).toContainText("Confirmed by a User.");
  expect((await generateVatReport(client, { companyId, period: "2026-10" })).ok).toBe(true);
  expect(await finalizeVatReport(client, { companyId, period: "2026-10", confirmed: true })).toEqual({ ok: true, value: null });
  await page.reload();
  await expect(page.getByLabel("First eligible period", { exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Save reporting period", exact: true })).toHaveCount(0);
  const reverse = await createManualDocument(client, { companyId, payload: { ...SAMPLE_EXTRACTION, taxPointDate: "2026-11-01", proposedVatRegime: "domestic_reverse_charge", reverseChargeCode: "4" } }, undefined, fakeVatPayerRegistry());
  if (!reverse.ok) throw new Error(reverse.error);
  await page.goto(`/companies/${companyId}/documents/${reverse.value.id}`);
  await expect(page.getByRole("group", { name: "Earliest Claim Period", exact: true })).toHaveCount(0);
  await expect(page.locator('select[name="claimedReportingPeriod"]')).toHaveCount(0);
});
