import { provisionAndLogIn } from "./support/accounts";
import { expect, test } from "@playwright/test";
import { addBrowserDocumentWarningFixture, assignBrowserAiConfigurationFixture } from "../tests/support/e2e";

test("bank advisories stay distinct through correction, approval and Finalization", async ({ context, page, baseURL }) => {
  if (!baseURL) throw new Error("Playwright base URL is required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  await provisionAndLogIn(page, { organizationName: `Bank advisory ${run}`, email: `bank-advisory-${run}@example.test`, password: "Playwright-password-139" });
  await expect(page).toHaveURL(/\/companies\/new$/);
  await page.getByLabel("Company name").fill(`Bank Company ${run}`);
  await page.getByLabel("IČO").fill("25596641");
  await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská");
  await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha");
  await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/filing-frequency$/);
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  await assignBrowserAiConfigurationFixture(companyId);
  await page.goto(`/companies/${companyId}/upload`);
  await page.locator('input[type="file"]:not([capture])').setInputFiles("tests/fixtures/receipt.png");
  await page.getByRole("button", { name: "Upload batch", exact: true }).click();
  await page.getByRole("link", { name: "Review 1 Document", exact: true }).click({ timeout: 45_000 });
  await page.getByRole("table", { name: "Documents", exact: true }).getByRole("link").first().click();
  await expect(page).toHaveURL(/\/documents\/[0-9a-f-]+(?:\?.*)?$/);
  await expect(page.getByRole("button", { name: "Approve version 1", exact: true })).toBeVisible();
  const documentId = new URL(page.url()).pathname.split("/").at(-1)!;

  await page.getByLabel("Bank account", { exact: true }).fill("000000-123456789/0100");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 2", exact: true })).toBeVisible();
  await expect(page.getByText("The payment account is not published for this supplier in the VAT payer registry.", { exact: true })).toHaveCount(0);

  await page.getByLabel("Bank account", { exact: true }).fill("2000145399/0800");
  await page.getByLabel("IBAN", { exact: true }).fill("CZ6508000000192000145399");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 3", exact: true })).toBeVisible();
  const inconsistent = "The domestic account number and IBAN identify different payment accounts. Correct the payment details; publication remains undetermined. You can still approve the Document.";
  await expect(page.getByText(inconsistent, { exact: true })).toBeVisible();
  await expect(page.getByText("The payment account is not published for this supplier in the VAT payer registry.", { exact: true })).toHaveCount(0);
  await context.addCookies([{ name: "NEXT_LOCALE", value: "cs", url: baseURL }]);
  await page.reload();
  await expect(page.getByText("Tuzemské číslo účtu a IBAN označují různé platební účty. Opravte platební údaje; zveřejnění účtu zůstává neurčené. Doklad můžete přesto schválit.", { exact: true })).toBeVisible();
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  await page.reload();

  await page.getByLabel("Bank account", { exact: true }).fill("19-2000145399/0800");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 4", exact: true })).toBeVisible();
  await expect(page.getByText(inconsistent, { exact: true })).toHaveCount(0);
  await expect(page.getByText("The payment account is not published for this supplier in the VAT payer registry.", { exact: true })).toHaveCount(1);

  await page.getByLabel("Bank account", { exact: true }).fill("gateway-order-123");
  await page.getByLabel("IBAN", { exact: true }).fill("");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 5", exact: true })).toBeVisible();
  await expect(page.getByText("The payment identifier is not a recognized bank account, so its publication could not be verified. Check the payment details manually; you can still approve the Document.", { exact: true })).toBeVisible();
  await expect(page.getByText("The payment account is not published for this supplier in the VAT payer registry.", { exact: true })).toHaveCount(0);

  await page.getByLabel("Bank account", { exact: true }).fill("");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 6", exact: true })).toBeVisible();
  const missing = "No payment account is entered. Check the payment details; you can still approve the Document.";
  const unpublished = "The payment account is not published for this supplier in the VAT payer registry.";
  const unavailable = "The VAT payer registry was unavailable, so the supplier and payment account check was not performed.";
  await expect(page.getByText(missing, { exact: true })).toBeVisible();
  await expect(page.getByText(unpublished, { exact: true })).toHaveCount(0);

  await page.getByLabel("Bank account", { exact: true }).fill("999999/0100");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 7", exact: true })).toBeVisible();
  await expect(page.getByText(unpublished, { exact: true })).toBeVisible();
  await expect(page.getByText(missing, { exact: true })).toHaveCount(0);
  // Existing immutable-Version fixture represents an unavailable registry result;
  // application tests separately exercise the actual unavailable/throwing port.
  await addBrowserDocumentWarningFixture(documentId);
  await page.reload();
  await expect(page.getByText(unavailable, { exact: true })).toBeVisible();
  await expect(page.getByText(unpublished, { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Approve version 8", exact: true }).click();
  await expect(page).toHaveURL(/\/documents(?:\?.*)?$/);
  await page.goto(`/companies/${companyId}/vat-reports?period=2026-10`);
  await page.getByRole("button", { name: "Generate draft", exact: true }).click();
  await page.getByRole("checkbox", { name: "I understand that Finalization creates a Period Lock for this snapshot.", exact: true }).check();
  await page.getByRole("button", { name: "Finalize and lock period", exact: true }).click();
  await expect(page.getByRole("button", { name: "Unlock period", exact: true })).toBeVisible();
  await page.goto(`/companies/${companyId}/documents/${documentId}`);
  const checks = page.getByRole("region", { name: "Bank Account Check", exact: true });
  await expect(checks.getByText("No manual refresh for the current Document data. Existing findings remain visible.", { exact: true })).toBeVisible();
  await expect(page.getByText(unavailable, { exact: true })).toBeVisible();
  await checks.getByRole("button", { name: "Check payment account again", exact: true }).click();
  await expect(checks.getByRole("status")).toBeVisible();
  await expect(checks.getByRole("status")).toContainText("The payment account was checked and is not published for the supplier.");
  await expect(checks.getByRole("status")).toContainText("Checked:");
  await expect(page.getByText(unavailable, { exact: true })).toHaveCount(0);
  await expect(page.getByText(unpublished, { exact: true })).toHaveCount(0);
  await expect(page.getByText("Approved", { exact: true })).toBeVisible();
  await expect(page.getByText("Reporting period 2026-10 is locked.", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Return to review", exact: true })).toHaveCount(0);
  await checks.getByText("Bank Account Check history", { exact: true }).click();
  await expect(checks.getByRole("link", { name: "Extraction Version 8", exact: true })).toBeVisible();
  await checks.getByRole("link", { name: "Extraction Version 8", exact: true }).click();
  await expect(page.getByText(unavailable, { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Check payment account again", exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "Show the current version", exact: true }).click();
  await expect(checks.getByRole("status")).toContainText("Checked:");
  await expect(page.getByText(unavailable, { exact: true })).toHaveCount(0);

  await expect(page.getByRole("link", { name: /Version 9/ })).toHaveCount(0);
  await context.addCookies([{ name: "NEXT_LOCALE", value: "cs", url: baseURL }]);
  await page.reload();
  const csChecks = page.getByRole("region", { name: "Ověření bankovního účtu", exact: true });
  await expect(csChecks.getByRole("button", { name: "Znovu ověřit platební účet", exact: true })).toBeVisible();
  await expect(csChecks.getByRole("status")).toBeVisible();
  await csChecks.getByRole("button", { name: "Znovu ověřit platební účet", exact: true }).click();
  await csChecks.getByText("Historie ověření bankovního účtu", { exact: true }).click();
  await expect(csChecks.getByRole("listitem")).toHaveCount(2);
  await page.goto(`/companies/${companyId}/vat-reports?period=2026-10`);
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  await page.reload();
  await expect(page.getByRole("button", { name: "Unlock period", exact: true })).toBeVisible();

});
