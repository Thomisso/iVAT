import { expect, test } from "@playwright/test";
import { provisionAndLogIn } from "./support/accounts";
import { addBrowserUnsplitSourceFixture } from "../tests/support/e2e";

test("a User defines actual workbook sheets and rows, keeps refused input and manually saves without a document image", async ({ page, context, baseURL }) => {
  if (!baseURL) throw new Error("Playwright base URL is required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  const email = `workbook-${run}@example.test`; const password = "Workbook-recovery-password-178";
  await provisionAndLogIn(page, { organizationName: `Workbook recovery ${run}`, email, password });
  await page.getByLabel("Company name").fill(`Workbook Company ${run}`);
  await page.getByLabel("IČO").fill("25596641"); await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská"); await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha"); await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  const source = await addBrowserUnsplitSourceFixture({ companyId, email, password, fileName: "invoice-list.xlsx" });
  await page.goto(`/companies/${companyId}/source-files/${source.sourceFileId}`);
  const original = await page.getByRole("link", { name: "Download the original workbook", exact: true }).getAttribute("href");
  if (!original) throw new Error("Original download is missing");
  const originalBytes = await (await page.request.get(original)).body();
  await page.getByRole("button", { name: "Define Documents manually", exact: true }).click();
  const ranges = page.getByRole("group", { name: "Document worksheet ranges", exact: true });
  await expect(ranges).toBeVisible();
  await expect(ranges.getByRole("combobox", { name: "Worksheet", exact: true })).toHaveValue("Přijaté účty");
  await ranges.getByLabel("First row", { exact: true }).fill("2");
  await ranges.getByLabel("Last row", { exact: true }).fill("3");
  await page.getByRole("button", { name: "Add Document range", exact: true }).click();
  await ranges.getByRole("combobox", { name: "Worksheet", exact: true }).nth(1).selectOption("Přijaté účty");
  await ranges.getByLabel("First row", { exact: true }).nth(1).fill("3");
  await ranges.getByLabel("Last row", { exact: true }).nth(1).fill("4");
  await page.getByRole("button", { name: "Save Document boundaries", exact: true }).click();
  await expect(page.getByText("Enter ascending, non-overlapping row ranges within the actual worksheet.", { exact: true })).toBeVisible();
  await expect(ranges.getByRole("combobox", { name: "Worksheet", exact: true }).nth(1)).toHaveValue("Přijaté účty");
  await expect(ranges.getByLabel("Last row", { exact: true }).nth(1)).toHaveValue("4");
  await page.getByRole("button", { name: "Remove range", exact: true }).nth(0).click();
  await expect(ranges.getByLabel("First row", { exact: true })).toHaveValue("3");
  await expect(ranges.getByLabel("Last row", { exact: true })).toHaveValue("4");
  await page.getByRole("button", { name: "Add Document range", exact: true }).click();
  await ranges.getByRole("combobox", { name: "Worksheet", exact: true }).nth(1).selectOption("Issued");
  await ranges.getByLabel("First row", { exact: true }).nth(1).fill("2");
  await ranges.getByLabel("Last row", { exact: true }).nth(1).fill("3");
  await page.getByRole("button", { name: "Save Document boundaries", exact: true }).click();
  const documents = page.getByRole("table", { name: "Documents", exact: true });
  await expect(documents.getByText("Needs review", { exact: true })).toHaveCount(2);
  await page.reload();
  await expect(documents.getByText("Needs review", { exact: true })).toHaveCount(2);
  expect(await (await page.request.get(original)).body()).toEqual(originalBytes);
  await documents.getByRole("link", { name: "Přijaté účty, rows 3–4", exact: true }).click();
  await expect(page.getByText("This Document came from spreadsheet rows and has no document image.", { exact: true })).toBeVisible();
  await expect(page.locator("pre")).toHaveText('[Sheet "Přijaté účty"]\n1\tDocument number\tGross amount\n3\tMANUAL-2\t242\n4\tMANUAL-3\t363');
  await expect(page.getByLabel("Tax point date", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByLabel("Tax point date", { exact: true })).toBeFocused();
  await page.getByLabel("Tax point date", { exact: true }).fill("15.10.2026");
  await page.getByLabel("Document number", { exact: true }).fill(`WORKBOOK-${run}`);
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 1", exact: true })).toBeVisible();
});
