import { provisionAndLogIn } from "./support/accounts";
import { expect, test } from "@playwright/test";

test("timing warnings stay independent and permit direct wizard and detail XML downloads", async ({ page, context, baseURL }, testInfo) => {
  if (!baseURL) throw new Error("Playwright baseURL is required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = crypto.randomUUID();
  await provisionAndLogIn(page, { organizationName: `Timing ${run}`, email: `timing-${run}@example.test`, password: "Playwright-password-141" });
  await page.getByLabel("Company name").fill("Timing Company");
  await page.getByLabel("IČO").fill("12345678");
  await page.getByLabel("VAT ID").fill("CZ12345678");
  await page.getByLabel("Street name").fill("Dlouhá");
  await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha");
  await page.getByLabel("Postal code").fill("11000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyUrl = page.url().replace(/\/setup\/ai-processing$/, "");
  await page.goto(`${companyUrl}/settings/vat`);
  await page.getByRole("combobox", { name: "Tax office", exact: true }).selectOption("451");
  await page.getByLabel("Economic activity (CZ-NACE)").fill("621000");
  await page.getByLabel("First name").fill("Jana");
  await page.getByLabel("Last name").fill("Nováková");
  await page.getByLabel("Capacity (e.g. director)").fill("director");
  await page.getByRole("button", { name: "Save filing defaults", exact: true }).click();
  await expect(page.getByRole("status").getByText("Filing defaults saved.")).toBeVisible();
  await page.clock.setFixedTime(new Date("2026-03-01T12:00:00Z"));
  await page.goto(`${companyUrl}/vat-reports?period=2026-03`);
  await page.getByRole("button", { name: "Generate draft", exact: true }).click();
  const card = page.locator(".vat-export-card").filter({ has: page.getByRole("heading", { name: /DPHDP3/ }) });
  await expect(card.getByText("The Reporting Period has not ended yet.", { exact: true })).toBeVisible();
  const direct = page.waitForEvent("download");
  await card.getByRole("button", { name: "Export VAT Return XML", exact: true }).click();
  expect((await direct).suggestedFilename()).toBe("DRAFT_DPHDP3_2026-03.xml");
  await card.getByRole("button", { name: "Edit for this export", exact: true }).click();
  await card.getByLabel("Preparation date", { exact: true }).fill("01.05.2026");
  await card.getByRole("button", { name: "Use saved defaults", exact: true }).click();
  await card.getByRole("button", { name: "Edit for this export", exact: true }).click();
  await expect(card.getByLabel("Preparation date", { exact: true })).toHaveValue("01.05.2026");

  await page.goto(`${companyUrl}/vat-reports/2026-03/vat-return`);
  await card.getByLabel("Preparation date", { exact: true }).fill("01.05.2026");
  await expect(card.getByText("The preparation date is after today in Prague.", { exact: true })).toBeVisible();
  await expect(card.getByText("The Reporting Period has not ended yet.", { exact: true })).toBeVisible();
  await expect(card.getByText(/Potentially late ordinary filing/)).toContainText("27.04.2026");

  for (const width of [360, 720]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
    const action = card.getByRole("button", { name: "Download XML", exact: true });
    await action.scrollIntoViewIfNeeded();
    const bounds = await action.boundingBox();
    if (!bounds) throw new Error("XML download control is not rendered");
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width);
    await testInfo.attach(`export-timing-${width}`, { body: await card.screenshot({ path: testInfo.outputPath(`export-timing-${width}.png`) }), contentType: "image/png" });
  }
  const detail = page.waitForEvent("download");
  await card.getByRole("button", { name: "Download XML", exact: true }).click();
  expect((await detail).suggestedFilename()).toBe("DRAFT_DPHDP3_2026-03.xml");
  await card.getByLabel("Preparation date", { exact: true }).fill("31.02.2026");
  await card.getByRole("button", { name: "Download XML", exact: true }).click();
  await expect(card.getByText("Enter a valid date as dd.mm.yyyy.", { exact: true })).toBeVisible();
  await expect(card.getByText("The preparation date is after today in Prague.", { exact: true })).toHaveCount(0);
  await card.getByLabel("Preparation date", { exact: true }).fill("01.03.2026");
  await expect(card.getByText("The preparation date is after today in Prague.", { exact: true })).toHaveCount(0);
  await expect(card.getByText(/Potentially late ordinary filing/)).toHaveCount(0);
  await expect(card.getByText("The Reporting Period has not ended yet.", { exact: true })).toBeVisible();
  await page.clock.setFixedTime(new Date("2026-04-27T21:59:00Z"));
  await page.reload();
  await card.getByLabel("Preparation date", { exact: true }).fill("27.04.2026");
  await expect(card.getByText(/Potentially late ordinary filing/)).toHaveCount(0);
  await page.clock.setFixedTime(new Date("2026-04-27T22:00:00Z"));
  await page.bringToFront();
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(card.getByText(/Potentially late ordinary filing/)).toBeVisible();

  await context.addCookies([{ name: "NEXT_LOCALE", value: "cs", url: baseURL }]);
  await page.reload();
  await expect(card.getByText(/Možné opožděné řádné podání/)).toBeVisible();
});
