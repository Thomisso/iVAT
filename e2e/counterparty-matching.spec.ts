import { expect, test } from "@playwright/test";
import { provisionAndLogIn } from "./support/accounts";
import { browserUserClient } from "../tests/support/e2e";
import { SAMPLE_EXTRACTION } from "../src/ai/fake";
import { createManualDocument, getDocument, listExtractionVersions } from "../src/application/documents";
import { archiveCounterparty, createCounterparty, getCounterparty, listCounterparties } from "../src/application/counterparties";
import { fakeVatPayerRegistry } from "../src/vat-registry/fake";

test("identity matching, deliberate unlink, no-ID consent and explicit archived restoration preserve the reviewed Party", async ({ page, context, baseURL }) => {
  if (!baseURL) throw new Error("base URL required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = crypto.randomUUID();
  await provisionAndLogIn(page, { organizationName: `Matching ${run}`, email: `matching-${run}@example.test`, password: "Matching-browser-password-234" });
  await page.getByLabel("Company name").fill(`Matching ${run}`);
  await page.getByLabel("IČO").fill("25596641");
  await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská");
  await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha");
  await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  const client = await browserUserClient(await context.cookies());
  if (process.env.IVAT_234_BROWSER_STATE) await context.storageState({ path: process.env.IVAT_234_BROWSER_STATE });
  const party = SAMPLE_EXTRACTION.supplier;
  const known = await createCounterparty(client, { companyId, name: party.name!, ico: party.ico, vatId: party.vatId,
    street: party.street!, city: party.city!, postalCode: party.postalCode!, countryCode: party.country!, supplier: true, customer: false });
  if (!known.ok) throw new Error(known.error);
  const payload = { ...SAMPLE_EXTRACTION, claimEligibility: { period: "2026-10", origin: "user" as const, confirmed: true } };
  const first = await createManualDocument(client, { companyId, payload }, undefined, fakeVatPayerRegistry());
  if (!first.ok) throw new Error(first.error);
  const href = (id: string) => `/companies/${companyId}/documents/${id}`;
  await page.goto(href(first.value.id));
  const directory = page.getByRole("group", { name: "Counterparty Directory", exact: true });
  await expect(directory).toContainText("Linked Counterparty: Dodavatel s.r.o.");
  const supplierName = page.getByRole("group", { name: "Supplier", exact: true }).getByLabel("Name", { exact: true });
  await expect(supplierName).toHaveValue("Dodavatel s.r.o.");
  await directory.getByRole("button", { name: "Remove link", exact: true }).click();
  await page.getByRole("button", { name: "Save corrections", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 2", exact: true })).toBeVisible();
  expect((await listExtractionVersions(client, companyId, first.value.id))[1].payload.counterpartyLink).toBeNull();
  await directory.getByRole("button", { name: "Use automatic matching", exact: true }).click();
  await page.getByRole("button", { name: "Save corrections", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 3", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Approve version 3", exact: true }).click();
  await expect(page).toHaveURL(/\/documents(?:\?.*)?$/);
  expect(await listExtractionVersions(client, companyId, first.value.id)).toHaveLength(3);
  expect((await listCounterparties(client, companyId)).total).toBe(1);

  const noId = await createManualDocument(client, { companyId, payload: { ...payload, documentNumber: "NO-ID-234",
    supplier: { ...party, name: "Cash supplier", ico: null, vatId: null } } }, undefined, fakeVatPayerRegistry());
  if (!noId.ok) throw new Error(noId.error);
  await page.goto(href(noId.value.id));
  const consent = page.getByRole("checkbox", { name: "Create a new Counterparty without IČO or VAT ID when approving this Document", exact: true });
  await expect(consent).not.toBeChecked();
  await page.getByRole("button", { name: "Approve version 1", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Resolve the Counterparty identity before approval." })).toBeVisible();
  expect((await listCounterparties(client, companyId)).total).toBe(1);
  await consent.check();
  await supplierName.fill("Cash supplier changed");
  await expect(consent).not.toBeChecked();
  await consent.check();
  await page.getByRole("button", { name: "Approve version 1", exact: true }).click();
  await expect(page.getByRole("status", { name: "Warnings for these submitted values", exact: true })).toBeVisible();
  await expect(supplierName).toHaveValue("Cash supplier changed");
  expect((await listCounterparties(client, companyId)).total).toBe(1);
  await page.getByRole("button", { name: "Approve these values with warnings", exact: true }).click();
  await expect(page).toHaveURL(/\/documents(?:\?.*)?$/);
  expect((await getDocument(client, companyId, noId.value.id))?.status).toBe("approved");
  expect(await listCounterparties(client, companyId)).toMatchObject({ total: 2, entries: expect.arrayContaining([expect.objectContaining({ name: "Cash supplier changed", ico: null, vatId: null })]) });
  const saved = (await listExtractionVersions(client, companyId, noId.value.id))[1].payload;
  expect(saved.supplier.name).toBe("Cash supplier changed");
  expect(saved.counterpartyLink?.recorded?.name).toBe("Cash supplier changed");
  expect(saved).not.toHaveProperty("counterpartyCreationConsent");

  const archivedParty = { ...party, name: "Archived supplier 234", ico: "45274649", vatId: "CZ45274649" };
  const archived = await createCounterparty(client, { companyId, name: archivedParty.name!, ico: archivedParty.ico, vatId: archivedParty.vatId,
    street: party.street!, city: party.city!, postalCode: party.postalCode!, countryCode: party.country!, supplier: true, customer: false });
  if (!archived.ok) throw new Error(archived.error);
  expect(await archiveCounterparty(client, { companyId, id: archived.value.id })).toEqual({ ok: true, value: null });
  const third = await createManualDocument(client, { companyId, payload: { ...payload, documentNumber: "ARCHIVED-234", supplier: archivedParty } }, undefined, fakeVatPayerRegistry());
  if (!third.ok) throw new Error(third.error);
  await page.goto(href(third.value.id));
  await page.getByRole("button", { name: "Approve version 1", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Resolve the Counterparty identity before approval." })).toBeVisible();
  expect((await getCounterparty(client, companyId, archived.value.id))?.archivedAt).toEqual(expect.any(String));
  await page.getByRole("link", { name: "Find an archived identity", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/counterparties\\?state=archived&ico=45274649&vatId=CZ45274649$`));
  await page.getByRole("link", { name: "Archived supplier 234", exact: true }).click();
  await page.getByRole("button", { name: "Restore Counterparty", exact: true }).click();
  await expect(page.getByText("Archived Counterparty", { exact: true })).toHaveCount(0);
  await page.goto(href(third.value.id));
  await expect(directory).toContainText("Archived supplier 234");
  await page.getByRole("button", { name: "Approve version 1", exact: true }).click();
  await expect(page).toHaveURL(/\/documents(?:\?.*)?$/);
  expect((await listCounterparties(client, companyId)).total).toBe(3);
  expect((await listExtractionVersions(client, companyId, third.value.id))[1].payload.counterpartyLink?.id).toBe(archived.value.id);
});
