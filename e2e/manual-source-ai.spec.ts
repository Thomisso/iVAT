import { expect, test } from "@playwright/test";
import { provisionAndLogIn } from "./support/accounts";
import { multiSheetWorkbookFile } from "../tests/support/files";
import { addBrowserManualDocumentFixture, assignBrowserAiConfigurationFixture, makeBrowserAiProviderUnavailableFixture } from "../tests/support/e2e";

for (const locale of ["en", "cs"] as const) test(`manual original attachment and explicit AI replacement preserve identity and require new human review (${locale})`, async ({ page, context, baseURL }) => {
  if (!baseURL) throw new Error("Playwright base URL is required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  const email = `manual-source-${run}@example.test`; const password = "Manual-source-browser-175";
  await provisionAndLogIn(page, { organizationName: `Manual Source ${run}`, email, password });
  await page.getByLabel("Company name").fill(`Manual Source ${run}`);
  await page.getByLabel("IČO").fill("25596641"); await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská"); await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha"); await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  const documentId = await addBrowserManualDocumentFixture({ companyId, email, password });
  await context.addCookies([{ name: "NEXT_LOCALE", value: locale, url: baseURL }]);
  const reviewUrl = `/companies/${companyId}/documents/${documentId}`;
  await page.goto(reviewUrl);
  const attach = page.getByRole("button", { name: locale === "en" ? "Attach original" : "Připojit originál", exact: true });
  const first = page.getByLabel(locale === "en" ? "First page" : "První strana", { exact: true });
  const last = page.getByLabel(locale === "en" ? "Last page" : "Poslední strana", { exact: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.locator(".review-original").screenshot({ path: `/tmp/ivat-spec-159/175-attach-${locale}-360.png` });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('input[type="file"]').setInputFiles("tests/fixtures/two-invoices.pdf");
  await first.fill("2"); await last.fill("3"); await attach.click();
  await expect(page.getByText(locale === "en" ? "Select an actual page range within the original." : "Vyberte skutečný rozsah stran v originálu.", { exact: true })).toBeVisible();
  await expect(first).toHaveValue("2"); await expect(last).toHaveValue("3");
  // React reset the native picker. The refused form retains the selected real original.
  await last.fill("2"); await attach.click();
  await expect(page.getByRole("link", { name: /two-invoices.pdf/ })).toBeVisible();
  await expect(attach).toHaveCount(0);
  await expect(page.getByLabel(locale === "en" ? "Document number" : "Číslo dokladu", { exact: true })).toHaveValue("MANUAL-BROWSER-175");
  await expect(page.getByRole("button", { name: locale === "en" ? "Return to review" : "Vrátit ke kontrole", exact: true })).toBeVisible();
  const runAi = page.getByRole("button", { name: locale === "en" ? "Run AI replacement" : "Spustit nahrazení pomocí AI", exact: true });
  const confirm = page.getByRole("checkbox", { name: locale === "en" ? "I understand that AI will replace the current values and withdraw approval." : "Rozumím, že AI nahradí aktuální hodnoty a odebere schválení.", exact: true });
  await confirm.check(); await runAi.click();
  await expect(page.getByText(locale === "en" ? "AI is not enabled or has no usable configuration. Your current values and approval are unchanged." : "AI není zapnuté nebo nemá použitelnou konfiguraci. Aktuální hodnoty a schválení zůstaly beze změny.", { exact: true })).toBeVisible();
  await expect(confirm).toBeChecked();
  await page.locator(".review-header").screenshot({ path: `/tmp/ivat-spec-159/175-confirm-${locale}.png` });
  await assignBrowserAiConfigurationFixture(companyId);
  await runAi.click();
  await expect(page.getByRole("button", { name: locale === "en" ? "Approve version 2" : "Schválit verzi 2", exact: true })).toBeVisible({ timeout: 40_000 });
  await expect(page.getByLabel(locale === "en" ? "Document number" : "Číslo dokladu", { exact: true })).toHaveValue("FV-2026-0001");
  await page.reload();
  await expect(page.getByRole("button", { name: locale === "en" ? "Approve version 2" : "Schválit verzi 2", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: /two-invoices.pdf/ })).toBeVisible();
  await page.screenshot({ path: `/tmp/ivat-spec-159/175-review-${locale}.png`, fullPage: true });
  await context.storageState({ path: `/tmp/ivat-spec-159/175-browser-${locale}-state.json` });
  await page.goto(`${reviewUrl}?version=1`);
  await expect(page.getByLabel(locale === "en" ? "Document number" : "Číslo dokladu", { exact: true })).toHaveValue("MANUAL-BROWSER-175");
  // The same attachment form also validates real worksheet ranges, with no page-image claim.
  const workbookDocument = await addBrowserManualDocumentFixture({ companyId, email, password });
  await page.goto(`/companies/${companyId}/documents/${workbookDocument}`);
  await page.locator('input[type="file"]').setInputFiles({ name: "actual.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from(multiSheetWorkbookFile("xlsx")) });
  await page.getByLabel(locale === "en" ? "Worksheet" : "List", { exact: true }).fill("Issued");
  await page.getByLabel(locale === "en" ? "First row" : "První řádek", { exact: true }).fill("2");
  await page.getByLabel(locale === "en" ? "Last row" : "Poslední řádek", { exact: true }).fill("3");
  await attach.click();
  await expect(page.locator(".workbook-source pre")).toHaveText('[Sheet "Issued"]\n1\tDocument number\tGross amount\n2\tISSUED-1\t484\n3\tISSUED-2\t605');
  await page.reload();
  await expect(page.getByRole("button", { name: locale === "en" ? "Return to review" : "Vrátit ke kontrole", exact: true })).toBeVisible();
  await makeBrowserAiProviderUnavailableFixture(companyId);
  await confirm.check(); await runAi.click();
  await expect(page.locator(".review-header .iv-badge")).toHaveText(locale === "en" ? "AI processing is waiting for platform intervention." : "Zpracování AI čeká na zásah správce platformy.", { timeout: 40_000 });
  await expect(page.getByRole("button", { name: locale === "en" ? "Complete manually" : "Doplnit ručně", exact: true })).toBeVisible({ timeout: 40_000 });
  await expect(page.getByLabel(locale === "en" ? "Document number" : "Číslo dokladu", { exact: true })).toHaveValue("MANUAL-BROWSER-175");
  await expect(page.getByRole("button", { name: locale === "en" ? "Return to review" : "Vrátit ke kontrole", exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("button", { name: locale === "en" ? "Complete manually" : "Doplnit ručně", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: /Version 2|Verze 2/ })).toHaveCount(0);
  await page.getByRole("button", { name: locale === "en" ? "Complete manually" : "Doplnit ručně", exact: true }).click();
  await expect(page.getByRole("button", { name: locale === "en" ? "Approve version 1" : "Schválit verzi 1", exact: true })).toBeVisible();
});
