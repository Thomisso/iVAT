import { expect, test } from "@playwright/test";
import { provisionAndLogIn } from "./support/accounts";
import { addBrowserUnextractedDocumentFixture } from "../tests/support/e2e";

test("unextracted Documents recover manually or by reversible reasoned exclusion without AI configuration", async ({ page, context, baseURL }) => {
  if (!baseURL) throw new Error("Playwright base URL is required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  const email = `recovery-${run}@example.test`;
  const password = "Recovery-browser-password-176";
  await provisionAndLogIn(page, { organizationName: `Recovery Organization ${run}`, email, password });
  await page.getByLabel("Company name").fill(`Recovery Company ${run}`);
  await page.getByLabel("IČO").fill("25596641");
  await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská");
  await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha");
  await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  const failed = await addBrowserUnextractedDocumentFixture({ companyId, email, password, status: "failed" });
  await page.goto(`/companies/${companyId}/documents/${failed}`);
  await expect(page.getByRole("img", { name: "receipt.png", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Complete manually", exact: true }).click();
  await expect(page.getByLabel("Tax point date", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Save corrections", exact: true }).click();
  await expect(page.getByLabel("Tax point date", { exact: true })).toBeFocused();
  await page.getByLabel("Tax point date", { exact: true }).fill("15.10.2026");
  await page.getByLabel("Document number", { exact: true }).fill(`RECOVERED-${run}`);
  await page.getByRole("button", { name: "Save corrections", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 1", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Document number", { exact: true })).toHaveValue(`RECOVERED-${run}`);
  await page.getByLabel("Direction", { exact: true }).selectOption("incoming");
  await page.getByLabel("VAT regime", { exact: true }).selectOption("domestic");
  await page.getByLabel("Currency", { exact: true }).fill("CZK");
  await page.getByRole("group", { name: "Supplier", exact: true }).getByLabel("VAT ID", { exact: true }).fill("CZ27082440");
  await page.getByRole("button", { name: "Add rate", exact: true }).click();
  const rates = page.getByRole("group", { name: "Rate breakdown and totals", exact: true });
  await rates.getByRole("textbox", { name: "Rate (%)", exact: true }).fill("21");
  await rates.getByRole("textbox", { name: "Net", exact: true }).fill("100.00");
  await rates.getByRole("textbox", { name: "VAT", exact: true }).fill("21.00");
  await page.getByLabel("Total net", { exact: true }).fill("100.00");
  await page.getByLabel("Total VAT", { exact: true }).fill("21.00");
  await page.getByLabel("Total incl. VAT", { exact: true }).fill("121.00");
  await page.getByRole("button", { name: "Save corrections", exact: true }).click();
  await page.getByRole("button", { name: "Approve version 2", exact: true }).click();
  await expect(page).toHaveURL(url => url.pathname === `/companies/${companyId}/documents`);
  await page.goto(`/companies/${companyId}/documents/${failed}`);
  await expect(page.getByRole("group", { name: "Live VAT calculation" })).toContainText("Included in live calculation");
  const waiting = await addBrowserUnextractedDocumentFixture({ companyId, email, password, status: "waiting_for_platform" });
  await page.goto(`/companies/${companyId}/documents/${waiting}`);
  await page.getByLabel("Exclusion reason", { exact: true }).fill("  ");
  await page.getByRole("button", { name: "Reject", exact: true }).click();
  await expect(page.getByText("Enter an exclusion reason of 1–500 characters.", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Exclusion reason", { exact: true })).toHaveValue("  ");
  await page.getByLabel("Exclusion reason", { exact: true }).fill("Personal receipt");
  await page.getByRole("button", { name: "Reject", exact: true }).click();
  await expect(page).toHaveURL(url => url.pathname === `/companies/${companyId}/documents`);
  await page.goto(`/companies/${companyId}/documents/${waiting}`);
  await expect(page.getByText("Personal receipt", { exact: false })).toBeVisible();
  await expect(page.getByRole("img", { name: "receipt.png", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Reverse exclusion", exact: true }).click();
  await expect(page.getByLabel("Tax point date", { exact: true })).toBeVisible();
  await page.reload();
  await page.getByLabel("Exclusion reason", { exact: true }).fill("Confirmed personal receipt");
  await page.getByRole("button", { name: "Reject", exact: true }).click();
  await expect(page).toHaveURL(url => url.pathname === `/companies/${companyId}/documents`);
  await page.goto(`/companies/${companyId}/documents/${waiting}`);
  await expect(page.getByText("Confirmed personal receipt", { exact: false })).toBeVisible();
});
