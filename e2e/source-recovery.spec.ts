import { expect, test } from "@playwright/test";
import { provisionAndLogIn } from "./support/accounts";
import { addBrowserUnsplitSourceFixture } from "../tests/support/e2e";

test("manual Source recovery defines real PDF pages and resolves or restores an image without AI configuration", async ({ page, context, baseURL }) => {
  if (!baseURL) throw new Error("Playwright base URL is required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  const email = `source-${run}@example.test`; const password = "Source-recovery-password-177";
  await provisionAndLogIn(page, { organizationName: `Source recovery ${run}`, email, password });
  await page.getByLabel("Company name").fill(`Source Company ${run}`);
  await page.getByLabel("IČO").fill("25596641"); await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská"); await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha"); await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  const pdf = await addBrowserUnsplitSourceFixture({ companyId, email, password, fileName: "two-invoices.pdf" });
  await page.goto(`/companies/${companyId}/source-files/${pdf.sourceFileId}`);
  await page.getByRole("button", { name: "Define Documents manually", exact: true }).click();
  await expect(page.getByRole("group", { name: "Document page ranges", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add Document range", exact: true }).click();
  await page.getByLabel("First page", { exact: true }).nth(1).fill("2");
  await page.getByLabel("Last page", { exact: true }).nth(1).fill("2");
  await page.getByRole("button", { name: "Save Document boundaries", exact: true }).click();
  await expect(page.getByText("Enter ascending, non-overlapping page ranges within the actual Source.", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Last page", { exact: true }).nth(0)).toHaveValue("2");
  await expect(page.getByLabel("First page", { exact: true }).nth(1)).toHaveValue("2");
  await page.getByLabel("Last page", { exact: true }).nth(0).fill("1");
  await page.getByRole("button", { name: "Save Document boundaries", exact: true }).click();
  const documents = page.getByRole("table", { name: "Documents", exact: true });
  await expect(documents).toBeVisible();
  await expect(documents.getByText("Needs review", { exact: true })).toHaveCount(2);
  await page.reload();
  await documents.getByRole("link", { name: "1", exact: true }).click();
  await expect(page.getByLabel("Tax point date", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByLabel("Tax point date", { exact: true })).toBeFocused();
  await page.getByLabel("Tax point date", { exact: true }).fill("15.10.2026");
  await page.getByLabel("Document number", { exact: true }).fill(`PDF-${run}`);
  await page.getByLabel("Direction", { exact: true }).selectOption("incoming");
  await page.getByLabel("VAT regime", { exact: true }).selectOption("domestic");
  await page.getByLabel("Currency", { exact: true }).fill("CZK");
  await page.getByRole("group", { name: "Supplier", exact: true }).getByLabel("VAT ID", { exact: true }).fill("CZ27082440");
  await page.getByRole("button", { name: "Add rate", exact: true }).click();
  const rates = page.getByRole("group", { name: "Rate breakdown and totals", exact: true });
  await rates.getByRole("textbox", { name: "Rate (%)", exact: true }).fill("21");
  await rates.getByRole("textbox", { name: "Net", exact: true }).fill("100.00");
  await rates.getByRole("textbox", { name: "VAT", exact: true }).fill("21.00");
  await page.getByLabel("Total net", { exact: true }).fill("100.00"); await page.getByLabel("Total VAT", { exact: true }).fill("21.00"); await page.getByLabel("Total incl. VAT", { exact: true }).fill("121.00");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await page.getByRole("button", { name: "Approve version 1", exact: true }).click();
  const image = await addBrowserUnsplitSourceFixture({ companyId, email, password, fileName: "receipt.png" });
  await page.goto(`/companies/${companyId}/source-files/${image.sourceFileId}`);
  await page.getByLabel("Exclusion reason", { exact: true }).fill("  ");
  await page.getByRole("button", { name: "Exclude Source File", exact: true }).click();
  await expect(page.getByText("Enter an exclusion reason of 1–500 characters.", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Exclusion reason", { exact: true })).toHaveValue("  ");
  await page.getByLabel("Exclusion reason", { exact: true }).fill("Unusable photo");
  await page.getByRole("button", { name: "Exclude Source File", exact: true }).click();
  await expect(page.getByText("Excluded Source File. Its original is preserved.", { exact: true })).toBeVisible();
  await expect(page.getByRole("img", { name: "receipt.png", exact: true })).toBeVisible();
  await page.goto(`/companies/${companyId}/vat-reports?period=${image.period}`);
  await expect(page.getByRole("heading", { name: "Source Files before Split", exact: true })).toBeVisible();
  await expect(page.getByText("Unusable photo", { exact: false })).toBeVisible();
  await page.getByRole("link", { name: "receipt.png", exact: true }).click();
  await page.getByRole("button", { name: "Reverse Source exclusion", exact: true }).click();
  await page.getByRole("button", { name: "Create one Document manually", exact: true }).click();
  await expect(page).toHaveURL(/\/documents\/[0-9a-f-]+$/);
  await expect(page.getByLabel("Tax point date", { exact: true })).toHaveValue("");
  await expect(page.getByRole("img", { name: "receipt.png", exact: true })).toBeVisible();
  await page.getByLabel("Tax point date", { exact: true }).fill("15.10.2026");
  await page.getByLabel("Document number", { exact: true }).fill(`IMAGE-${run}`);
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 1", exact: true })).toBeVisible();
  const heic = await addBrowserUnsplitSourceFixture({ companyId, email, password, fileName: "receipt.heic" });
  await page.goto(`/companies/${companyId}/source-files/${heic.sourceFileId}`);
  await page.getByRole("button", { name: "Create one Document manually", exact: true }).click();
  await expect(page).toHaveURL(/\/documents\/[0-9a-f-]+$/);
  const sourceImage = page.getByRole("img", { name: "receipt.heic", exact: true });
  await expect.poll(() => sourceImage.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0);

});
