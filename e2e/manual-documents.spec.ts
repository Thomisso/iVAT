import { expect, test } from "@playwright/test";
import { provisionAndLogIn } from "./support/accounts";

test("a manual Document survives partial saves and approval without a file or AI configuration", async ({ page, context, baseURL }) => {
  if (!baseURL) throw new Error("Playwright base URL is required");
  await context.addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL }]);
  const run = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  await provisionAndLogIn(page, { organizationName: `Manual Organization ${run}`, email: `manual-${run}@example.test`, password: "Manual-browser-password-174" });
  await page.getByLabel("Company name").fill(`Manual Company ${run}`);
  await page.getByLabel("IČO").fill("25596641");
  await page.getByLabel("VAT ID").fill("CZ25596641");
  await page.getByLabel("Street name").fill("Vinohradská");
  await page.getByLabel("House number").fill("12");
  await page.getByLabel("City").fill("Praha");
  await page.getByLabel("Postal code").fill("12000");
  await page.getByRole("button", { name: "Create company", exact: true }).click();
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page).toHaveURL(/\/setup\/ai-processing$/);
  const companyId = new URL(page.url()).pathname.split("/")[2];
  await page.goto(`/companies/${companyId}/documents`);
  await page.getByRole("link", { name: "Enter a Document manually", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Enter a Document manually", exact: true })).toBeVisible();
  await page.getByLabel("Document number", { exact: true }).fill(`MANUAL-${run}`);
  await page.getByRole("button", { name: "Enter a Document manually", exact: true }).click();
  await expect(page.getByLabel("Tax point date", { exact: true })).toBeFocused();
  await page.getByLabel("Tax point date", { exact: true }).fill("15.10.2026");
  await page.getByRole("button", { name: "Enter a Document manually", exact: true }).click();
  await expect(page).toHaveURL(/\/documents\/[0-9a-f-]+$/);
  const reviewUrl = page.url();
  await expect(page.getByText("No Source File is attached to this Document.", { exact: true })).toBeVisible();
  await expect(page.getByText("Import date", { exact: false })).toHaveCount(0);
  await page.reload();
  await expect(page.getByLabel("Document number", { exact: true })).toHaveValue(`MANUAL-${run}`);
  await expect(page.getByLabel("Tax point date", { exact: true })).toHaveValue("15.10.2026");

  await page.getByRole("button", { name: "Add rate", exact: true }).click();
  const rates = page.getByRole("group", { name: "Rate breakdown and totals", exact: true });
  await rates.getByRole("textbox", { name: "Rate (%)", exact: true }).fill("21");
  await rates.getByRole("textbox", { name: "Net", exact: true }).fill("100.00");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 2", exact: true })).toBeVisible();
  await page.reload();
  await expect(rates.getByRole("textbox", { name: "Net", exact: true })).toHaveValue("100.00");
  await expect(rates.getByRole("textbox", { name: "VAT", exact: true })).toHaveValue("");
  await page.getByRole("combobox", { name: "Direction", exact: true }).selectOption("incoming");
  await page.getByRole("combobox", { name: "VAT regime", exact: true }).selectOption("domestic");
  await page.getByLabel("Currency", { exact: true }).fill("CZK");
  await rates.getByRole("textbox", { name: "Net", exact: true }).fill("8264.47");
  await rates.getByRole("textbox", { name: "VAT", exact: true }).fill("1735.54");
  await page.getByLabel("Total net", { exact: true }).fill("8264.47");
  await page.getByLabel("Total VAT", { exact: true }).fill("1735.54");
  await page.getByLabel("Total incl. VAT", { exact: true }).fill("10000.01");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 3", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Approve version 3", exact: true }).click();
  await expect(page.getByText("Enter the counterparty VAT ID required for this VAT Regime before approval.", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Approve version 3", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "Approve version 3", exact: true })).toBeVisible();
  await rates.getByRole("textbox", { name: "Net", exact: true }).fill("8264.46");
  await page.getByLabel("Total net", { exact: true }).fill("8264.46");
  await page.getByLabel("Total incl. VAT", { exact: true }).fill("10000.00");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve version 4", exact: true })).toBeVisible();
  for (const locale of ["cs", "en"] as const) {
    await context.addCookies([{ name: "NEXT_LOCALE", value: locale, url: baseURL }]);
    await page.reload();
    await expect(page.getByText(locale === "en"
      ? "No supplier VAT ID is entered in iVAT. This ordinary domestic Document is at or below CZK 10,000 including VAT and can be approved. Check the original document; approval does not confirm that it meets its legal requirements."
      : "V iVAT není vyplněno DIČ dodavatele. Tento běžný tuzemský doklad nepřesahuje 10 000 Kč včetně DPH a lze jej schválit. Zkontrolujte původní doklad; schválení nepotvrzuje splnění jeho zákonných náležitostí.", { exact: true })).toBeVisible();
  }
  await page.getByRole("button", { name: "Approve version 4", exact: true }).click();
  await expect(page).toHaveURL(/\/documents(?:\?.*)?$/);
  await page.goto(reviewUrl);
  await expect(page.getByRole("button", { name: "Return to review", exact: true })).toBeVisible();
  await expect(page.getByRole("group", { name: "Live VAT calculation" })).toContainText("Included in live calculation");
  await expect(page.getByText("No Source File is attached to this Document.", { exact: true })).toBeVisible();
  await page.goto(`/companies/${companyId}/vat-reports?period=2026-10`);
  await page.getByRole("button", { name: "Generate draft", exact: true }).click();
  await page.getByRole("navigation", { name: "Reporting Period destinations", exact: true }).getByRole("link", { name: "VAT Return", exact: true }).click();
  await expect(page.getByRole("table", { name: "VAT Return", exact: true })).toContainText("1,735.54");
});
