import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createTranslator } from "next-intl";

const root = fileURLToPath(new URL("../", import.meta.url));
const checking = process.argv.includes("--check");
const locales = ["cs", "en"];
const messages = Object.fromEntries(await Promise.all(locales.map(async locale => [
  locale, JSON.parse(await readFile(path.join(root, "messages", `${locale}.json`), "utf8")),
])));
const escapeHtml = value => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#39;");
const outputs = new Map();
let cli = await readFile(path.join(root, "supabase/config.toml"), "utf8");
let compose = await readFile(path.join(root, "docker-compose.rosti.yml"), "utf8");

// GoTrue shares each configured template/subject across requests. Both supported
// languages use the same native token; no application mailer or locale token is involved.
for (const [kind, namespace] of [["magic_link", "magicLink"], ["recovery", "recovery"]]) {
  const translators = locales.map(locale => createTranslator({ locale, messages: messages[locale], namespace: `authEmails.${namespace}` }));
  const subject = translators.map(t => t("subject")).join(" / ");
  const link = `{{ .RedirectTo }}&amp;token_hash={{ .TokenHash }}${kind === "magic_link" ? "&amp;type=magiclink" : ""}`;
  const sections = translators.map((t, index) => `<section lang="${locales[index]}">\n<h2>${escapeHtml(t("title"))}</h2>\n<p>${escapeHtml(t("intro"))}</p>\n<p><a href="${link}">${escapeHtml(t("action"))}</a></p>${kind === "recovery" ? `\n<p>${escapeHtml(t("ignore"))}</p>` : ""}\n</section>`);
  const html = `<!-- Generated by npm run auth:templates from next-intl messages. -->\n<!doctype html>\n<html><body>\n${sections.join("\n<hr>\n")}\n</body></html>\n`;
  outputs.set(`supabase/templates/${kind}.html`, html);
  outputs.set(`deploy/proxy/${kind}.html`, html);
  const cliSubject = new RegExp(`(\\[auth\\.email\\.template\\.${kind}\\]\\nsubject = )[^\\n]*`);
  const composeSubject = new RegExp(`(      GOTRUE_MAILER_SUBJECTS_${kind.toUpperCase()}: )[^\\n]*`);
  if (!cliSubject.test(cli) || !composeSubject.test(compose)) throw new Error(`Missing native Auth subject configuration: ${kind}`);
  cli = cli.replace(cliSubject, (_, prefix) => prefix + JSON.stringify(subject));
  compose = compose.replace(composeSubject, (_, prefix) => prefix + JSON.stringify(subject));
}
outputs.set("supabase/config.toml", cli);
outputs.set("docker-compose.rosti.yml", compose);
for (const [name, content] of outputs) {
  const file = path.join(root, name);
  if (checking) {
    if (await readFile(file, "utf8") !== content) throw new Error(`Native Auth copy is stale: ${name}. Run npm run auth:templates.`);
  } else {
    // Preserve existing file identities, including when an owner has a live bind mount.
    await writeFile(file, content);
  }
}
